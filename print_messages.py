#!/usr/bin/env python3
"""
Simple script to print hello world messages followed by a goodbye message.
"""


def main():
    """Print hello world twice, then bye world once."""
    # Print "hello world" twice
    for _ in range(2):
        print("hello world")

    # Print "bye world" once
    print("bye world")


if __name__ == "__main__":
    main()
